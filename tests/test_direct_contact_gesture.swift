import Foundation
#if canImport(CoreGraphics)
import CoreGraphics
#endif

@main struct DirectContactGestureTests {
    static func main() {
        var g = DirectContactGesture()
        let p = CGPoint(x: 100, y: 200), jitter = CGPoint(x: 103, y: 202), moved = CGPoint(x: 125, y: 200)
        for tool in [DirectContactGesture.Tool.finger, .pencil] {
            g.begin(p, tool: tool, time: 1)
            precondition(g.move(jitter).isEmpty, "jitter must never press the guest button")
            precondition(g.end(jitter, time: 1.2) == [.click(p, count: 1, secondary: false)])
            g.begin(p, tool: tool, time: 1.5)
            precondition(g.end(moved, time: 1.51).isEmpty, "a swipe without delivered move samples must not click")
            g.begin(p, tool: tool, time: 2)
            precondition(g.move(moved) == [.down(p), .move(moved)], "drag starts at the touched object")
            precondition(g.hold(time: 3).isEmpty, "a drag must not turn into right/double-click")
            precondition(g.end(moved, time: 3) == [.move(moved), .up(moved)])
            precondition(g.end(moved, time: 3).isEmpty, "no duplicate lift")
            g.begin(p, tool: tool, time: 4); g.reset()
            precondition(g.hold(time: 5).isEmpty && g.end(p, time: 5).isEmpty, "cancel/multitouch suppresses clicks")
        }
        g.begin(p, tool: .finger, time: 10)
        precondition(g.hold(time: 10.54).isEmpty)
        precondition(g.hold(time: 10.56) == [.click(p, count: 1, secondary: true)])
        precondition(g.move(moved).isEmpty && g.end(moved, time: 11).isEmpty, "context action consumes the gesture")
        g.begin(p, tool: .finger, time: 12)
        precondition(g.end(jitter, time: 13) == [.click(p, count: 1, secondary: true)], "late timer still gives right-click")
        g.begin(p, tool: .pencil, time: 14)
        precondition(g.hold(time: 15).isEmpty, "Pencil hold cannot click while still touching")
        precondition(g.end(jitter, time: 15) == [.click(p, count: 2, secondary: false)])
        g.begin(p, tool: .pencil, time: 16)
        precondition(g.hold(time: 17).isEmpty)
        precondition(g.move(moved) == [.down(p), .move(moved)], "held Pencil may still drag")
        precondition(g.end(moved, time: 18) == [.move(moved), .up(moved)])
        for t in [20.0, 20.15] {
            g.begin(p, tool: .finger, time: t)
            precondition(g.end(p, time: t + 0.05) == [.click(p, count: 1, secondary: false)])
        }
        // Opt-in scroll never changes the default drag or Pencil semantics.
        g.begin(p, tool: .finger, time: 25, scrollFingerSwipes: true)
        precondition(g.move(moved, time: 25.05) == [.scrollBegin(p, time: 25), .scroll(moved, time: 25.05)])
        precondition(g.hold(time: 26).isEmpty, "scroll cannot become context click")
        precondition(g.end(moved, time: 26) == [.scroll(moved, time: 26), .scrollEnd(time: 26)])
        g.begin(p, tool: .finger, time: 27, scrollFingerSwipes: true)
        precondition(g.move(moved, time: 27.25) == [.down(p), .move(moved)], "pause then move retains drag")
        precondition(g.end(moved, time: 27.3) == [.move(moved), .up(moved)])
        g.begin(p, tool: .finger, time: 28, scrollFingerSwipes: true)
        precondition(g.hold(time: 28.56) == [.click(p, count: 1, secondary: true)])
        precondition(g.end(p, time: 28.6).isEmpty)
        g.begin(p, tool: .finger, time: 29, scrollFingerSwipes: true)
        precondition(g.end(jitter, time: 29.1) == [.click(p, count: 1, secondary: false)])
        g.begin(p, tool: .finger, time: 29.2, scrollFingerSwipes: true)
        precondition(g.end(moved, time: 29.25) == [.scrollBegin(p, time: 29.2), .scroll(moved, time: 29.25), .scrollEnd(time: 29.25)], "unsampled flick scrolls without clicking")
        g.begin(p, tool: .pencil, time: 29.4, scrollFingerSwipes: true)
        precondition(g.move(moved, time: 29.45) == [.down(p), .move(moved)])
        g.reset()
        // Tablet mode sends actual contact immediately, including a stationary
        // dot/pressure change; it must never synthesize desktop double-clicks.
        precondition(g.begin(p, tool: .pencil, time: 29.6, pencilTablet: true) == [.down(p)])
        precondition(g.move(p, time: 29.61) == [.move(p)])
        precondition(g.move(jitter, time: 29.62) == [.move(jitter)])
        precondition(g.hold(time: 30.3).isEmpty)
        precondition(g.end(p, time: 30.4) == [.move(p), .up(p)])
        precondition(g.begin(p, tool: .pencil, time: 31, pencilTablet: true) == [.down(p)])
        g.reset()
        precondition(g.end(p, time: 31.1).isEmpty, "cancelled tablet stroke never recreates contact")
        precondition(g.begin(p, tool: .finger, time: 32, pencilTablet: true).isEmpty)
        precondition(g.end(p, time: 32.1) == [.click(p, count: 1, secondary: false)], "tablet mode changes Pencil only")
        var multi = DirectMultiTouchGate()
        g.begin(p, tool: .finger, time: 33, scrollFingerSwipes: true)
        precondition(g.canJoinContextTap(at: jitter) && !g.canJoinContextTap(at: moved))
        _ = g.move(moved, time: 33.1)
        precondition(!g.canJoinContextTap(at: p), "a scroll cannot become a two-finger context tap")
        g.begin(p, tool: .finger, time: 34)
        _ = g.move(moved, time: 34.3)
        precondition(!g.canJoinContextTap(at: p), "a drag cannot become a context tap")
        g.begin(p, tool: .finger, time: 35)
        _ = g.hold(time: 35.6)
        precondition(!g.canJoinContextTap(at: p), "a long press cannot click twice")
        g.reset()
        multi.begin(count: 2, time: 30)
        precondition(!multi.move(distance: 0, count: 2) && !multi.forwarding)
        precondition(!multi.move(distance: 7, count: 2) && !multi.reveal(time: 30.1), "two-finger tap emits no native trackpad input")
        precondition(!multi.move(distance: 10, count: 1), "lifting one finger cannot become a one-finger pointer jump")
        precondition(multi.move(distance: 10, count: 2) && multi.forwarding, "movement activates native scrolling")
        precondition(!multi.move(distance: 20, count: 2), "start native gesture only once")
        precondition(!multi.reveal(time: 30.2))
        multi.reset(); multi.begin(count: 2, time: 40); multi.begin(count: 4, time: 40.05)
        precondition(multi.reveal(time: 40.2), "four-finger control reveal still works without forwarding a tap")
        precondition(!multi.reveal(time: 41))
        multi.reset(); multi.begin(count: 4, time: 50)
        precondition(multi.move(distance: 9, count: 4) && !multi.reveal(time: 50.2))
        multi.reset(); multi.begin(count: 1, time: 60)
        precondition(!multi.move(distance: .nan, count: 1) && multi.move(distance: 9, count: 1))
        multi.reset(); multi.begin(count: 2, time: 70)
        precondition(multi.secondaryTap(time: 70.2), "opt-in context tap is independent of guest trackpad tap settings")
        precondition(!multi.secondaryTap(time: 70.4) && !multi.secondaryTap(time: 69))
        precondition(!multi.secondaryTap(time: .infinity))
        multi.record(distance: 9)
        precondition(!multi.secondaryTap(time: 70.2), "unsampled move on lift is not a tap")
        multi.reset(); multi.begin(count: 2, time: 80)
        precondition(multi.move(distance: 9, count: 2))
        precondition(!multi.secondaryTap(time: 80.1), "scroll must not end in context click")
        multi.reset(); multi.begin(count: 2, time: 90); multi.begin(count: 3, time: 90.01)
        precondition(!multi.secondaryTap(time: 90.1), "third finger permanently disqualifies context tap")
        multi.reset(); multi.begin(count: 2, time: 100)
        precondition(!multi.move(distance: 9, count: 1) && !multi.secondaryTap(time: 100.1), "movement after a partial lift cannot click")
        multi.reset(); multi.begin(count: 2, time: 110); multi.record(distance: .nan)
        precondition(!multi.secondaryTap(time: 110.1))
        multi.reset()
        precondition(!multi.secondaryTap(time: 110.1), "cancelled gesture cannot click")
        print("PASS: finger/Pencil jitter, clicks, double-click, hold context menu, drag and cancellation")
    }
}
