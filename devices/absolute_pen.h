#define HV_PEN_REPORT_LEN 13
#define HV_PEN_REPORTS 128
#define HV_PEN_TIP 1
#define HV_PEN_BARREL 2
#define HV_PEN_RANGE 4
#define HV_PEN_INVERT 8
