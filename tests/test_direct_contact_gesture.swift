import Foundation
#if canImport(CoreGraphics)
import CoreGraphics
#endif

@main struct DirectContactGestureTests {
    static func main() {
        var g = DirectContactGesture()
        let p = CGPoint(x: 100, y: 200), jitter = CGPoint(x: 103, y: 202), moved = CGPoint(x: 125, y: 200)
        for tool in [DirectContactGesture.Tool.finger, .pencil] {
            g.begin(p, tool: tool, time: 1)
            precondition(g.move(jitter).isEmpty, "jitter must never press the guest button")
            precondition(g.end(jitter, time: 1.2) == [.click(p, count: 1, secondary: false)])
            g.begin(p, tool: tool, time: 1.5)
            precondition(g.end(moved, time: 1.51).isEmpty, "a swipe without delivered move samples must not click")
            g.begin(p, tool: tool, time: 2)
            precondition(g.move(moved) == [.down(p), .move(moved)], "drag starts at the touched object")
            precondition(g.hold(time: 3).isEmpty, "a drag must not turn into right/double-click")
            precondition(g.end(moved, time: 3) == [.move(moved), .up(moved)])
            precondition(g.end(moved, time: 3).isEmpty, "no duplicate lift")
            g.begin(p, tool: tool, time: 4); g.reset()
            precondition(g.hold(time: 5).isEmpty && g.end(p, time: 5).isEmpty, "cancel/multitouch suppresses clicks")
        }
        g.begin(p, tool: .finger, time: 10)
        precondition(g.hold(time: 10.54).isEmpty)
        precondition(g.hold(time: 10.56) == [.click(p, count: 1, secondary: true)])
        precondition(g.move(moved).isEmpty && g.end(moved, time: 11).isEmpty, "context action consumes the gesture")
        g.begin(p, tool: .finger, time: 12)
        precondition(g.end(jitter, time: 13) == [.click(p, count: 1, secondary: true)], "late timer still gives right-click")
        g.begin(p, tool: .pencil, time: 14)
        precondition(g.hold(time: 15).isEmpty, "Pencil hold cannot click while still touching")
        precondition(g.end(jitter, time: 15) == [.click(p, count: 2, secondary: false)])
        g.begin(p, tool: .pencil, time: 16)
        precondition(g.hold(time: 17).isEmpty)
        precondition(g.move(moved) == [.down(p), .move(moved)], "held Pencil may still drag")
        precondition(g.end(moved, time: 18) == [.move(moved), .up(moved)])
        for t in [20.0, 20.15] {
            g.begin(p, tool: .finger, time: t)
            precondition(g.end(p, time: t + 0.05) == [.click(p, count: 1, secondary: false)])
        }
        // Opt-in scroll never changes the default drag or Pencil semantics.
        g.begin(p, tool: .finger, time: 25, scrollFingerSwipes: true)
        precondition(g.move(moved, time: 25.05) == [.scrollBegin(p, time: 25), .scroll(moved, time: 25.05)])
        precondition(g.hold(time: 26).isEmpty, "scroll cannot become context click")
        precondition(g.end(moved, time: 26) == [.scroll(moved, time: 26), .scrollEnd(time: 26)])
        g.begin(p, tool: .finger, time: 27, scrollFingerSwipes: true)
        precondition(g.move(moved, time: 27.25) == [.down(p), .move(moved)], "pause then move retains drag")
        precondition(g.end(moved, time: 27.3) == [.move(moved), .up(moved)])
        g.begin(p, tool: .finger, time: 28, scrollFingerSwipes: true)
        precondition(g.hold(time: 28.56) == [.click(p, count: 1, secondary: true)])
        precondition(g.end(p, time: 28.6).isEmpty)
        g.begin(p, tool: .finger, time: 29, scrollFingerSwipes: true)
        precondition(g.end(jitter, time: 29.1) == [.click(p, count: 1, secondary: false)])
        g.reset() // an independent swipe, not tap-then-drag
        g.begin(p, tool: .finger, time: 29.2, scrollFingerSwipes: true)
        precondition(g.end(moved, time: 29.25) == [.scrollBegin(p, time: 29.2), .scroll(moved, time: 29.25), .scrollEnd(time: 29.25)], "unsampled flick scrolls without clicking")
        g.begin(p, tool: .pencil, time: 29.4, scrollFingerSwipes: true)
        precondition(g.move(moved, time: 29.45) == [.down(p), .move(moved)])
        g.reset()
        // Tablet mode sends actual contact immediately, including a stationary
        // dot/pressure change; it must never synthesize desktop double-clicks.
        precondition(g.begin(p, tool: .pencil, time: 29.6, pencilTablet: true) == [.down(p)])
        precondition(g.move(p, time: 29.61) == [.move(p)])
        precondition(g.move(jitter, time: 29.62) == [.move(jitter)])
        precondition(g.hold(time: 30.3).isEmpty)
        precondition(g.end(p, time: 30.4) == [.move(p), .up(p)])
        precondition(g.begin(p, tool: .pencil, time: 31, pencilTablet: true) == [.down(p)])
        g.reset()
        precondition(g.end(p, time: 31.1).isEmpty, "cancelled tablet stroke never recreates contact")
        precondition(g.begin(p, tool: .finger, time: 32, pencilTablet: true).isEmpty)
        precondition(g.end(p, time: 32.1) == [.click(p, count: 1, secondary: false)], "tablet mode changes Pencil only")
        var multi = DirectMultiTouchGate()
        g.begin(p, tool: .finger, time: 33, scrollFingerSwipes: true)
        precondition(g.canJoinContextTap(at: jitter) && !g.canJoinContextTap(at: moved))
        _ = g.move(moved, time: 33.1)
        precondition(!g.canJoinContextTap(at: p), "a scroll cannot become a two-finger context tap")
        g.begin(p, tool: .finger, time: 34)
        _ = g.move(moved, time: 34.3)
        precondition(!g.canJoinContextTap(at: p), "a drag cannot become a context tap")
        g.begin(p, tool: .finger, time: 35)
        _ = g.hold(time: 35.6)
        precondition(!g.canJoinContextTap(at: p), "a long press cannot click twice")
        g.reset()
        multi.begin(count: 2, time: 30)
        precondition(!multi.move(distance: 0, count: 2) && !multi.forwarding)
        precondition(!multi.move(distance: 7, count: 2) && !multi.reveal(time: 30.1), "two-finger tap emits no native trackpad input")
        precondition(!multi.move(distance: 10, count: 1), "lifting one finger cannot become a one-finger pointer jump")
        precondition(multi.move(distance: 10, count: 2) && multi.forwarding, "movement activates native scrolling")
        precondition(!multi.move(distance: 20, count: 2), "start native gesture only once")
        precondition(!multi.reveal(time: 30.2))
        multi.reset(); multi.begin(count: 2, time: 40); multi.begin(count: 4, time: 40.05)
        precondition(multi.reveal(time: 40.2), "four-finger control reveal still works without forwarding a tap")
        precondition(!multi.reveal(time: 41))
        multi.reset(); multi.begin(count: 4, time: 50)
        precondition(multi.move(distance: 9, count: 4) && !multi.reveal(time: 50.2))
        multi.reset(); multi.begin(count: 1, time: 60)
        precondition(!multi.move(distance: .nan, count: 1) && multi.move(distance: 9, count: 1))
        multi.reset(); multi.begin(count: 2, time: 70)
        precondition(multi.secondaryTap(time: 70.2), "opt-in context tap is independent of guest trackpad tap settings")
        precondition(!multi.secondaryTap(time: 70.4) && !multi.secondaryTap(time: 69))
        precondition(!multi.secondaryTap(time: .infinity))
        multi.record(distance: 9)
        precondition(!multi.secondaryTap(time: 70.2), "unsampled move on lift is not a tap")
        multi.reset(); multi.begin(count: 2, time: 80)
        precondition(multi.move(distance: 9, count: 2))
        precondition(!multi.secondaryTap(time: 80.1), "scroll must not end in context click")
        multi.reset(); multi.begin(count: 2, time: 90); multi.begin(count: 3, time: 90.01)
        precondition(!multi.secondaryTap(time: 90.1), "third finger permanently disqualifies context tap")
        multi.reset(); multi.begin(count: 2, time: 100)
        precondition(!multi.move(distance: 9, count: 1) && !multi.secondaryTap(time: 100.1), "movement after a partial lift cannot click")
        multi.reset(); multi.begin(count: 2, time: 110); multi.record(distance: .nan)
        precondition(!multi.secondaryTap(time: 110.1))
        multi.reset()
        precondition(!multi.secondaryTap(time: 110.1), "cancelled gesture cannot click")
        // Scroll and desktop drag need distinct intents. Tap once, then put
        // the finger back and move: this must drag even inside the scroll delay.
        var drag = DirectContactGesture()
        func tap(_ time: TimeInterval) {
            drag.begin(p, tool: .finger, time: time, scrollFingerSwipes: true)
            precondition(drag.end(p, time: time + 0.04) == [.click(p, count: 1, secondary: false)])
        }
        tap(120)
        drag.begin(p, tool: .finger, time: 120.1, scrollFingerSwipes: true)
        precondition(drag.move(jitter, time: 120.11).isEmpty)
        precondition(drag.move(moved, time: 120.12) == [.down(p), .move(moved)], "tap-then-drag must beat one-finger scrolling")
        precondition(drag.hold(time: 121).isEmpty)
        precondition(drag.end(moved, time: 121.1) == [.move(moved), .up(moved)])
        precondition(drag.end(moved, time: 121.2).isEmpty, "one drag release")
        tap(122); tap(122.1) // two stationary clicks remain a desktop double-click
        tap(123)
        drag.begin(p, tool: .finger, time: 123.1, scrollFingerSwipes: true)
        precondition(drag.end(moved, time: 123.12) == [.down(p), .move(moved), .up(moved)], "fast tap-drag with no move callback still releases")
        tap(124)
        drag.begin(p, tool: .finger, time: 124.5, scrollFingerSwipes: true)
        precondition(drag.move(moved, time: 124.51) == [.scrollBegin(p, time: 124.5), .scroll(moved, time: 124.51)], "expired tap cannot capture the next scroll")
        drag.reset(); tap(125)
        drag.begin(CGPoint(x: 200, y: 200), tool: .finger, time: 125.1, scrollFingerSwipes: true)
        precondition(drag.move(CGPoint(x: 225, y: 200), time: 125.12) == [.scrollBegin(CGPoint(x: 200, y: 200), time: 125.1), .scroll(CGPoint(x: 225, y: 200), time: 125.12)], "a tap elsewhere cannot arm drag")
        drag.reset(); tap(126); drag.reset()
        drag.begin(p, tool: .finger, time: 126.1, scrollFingerSwipes: true)
        precondition(drag.move(moved, time: 126.12) == [.scrollBegin(p, time: 126.1), .scroll(moved, time: 126.12)], "mode/scene/multitouch cancellation clears tap history")
        drag.reset(); tap(127)
        drag.begin(p, tool: .pencil, time: 127.1, scrollFingerSwipes: true)
        precondition(drag.end(p, time: 127.14) == [.click(p, count: 1, secondary: false)], "finger tap cannot change Pencil policy")
        drag.begin(p, tool: .finger, time: 128, scrollFingerSwipes: true)
        precondition(drag.end(p, time: .nan).isEmpty)
        drag.reset(); tap(129)
        drag.begin(p, tool: .finger, time: 129.1, scrollFingerSwipes: true)
        precondition(drag.hold(time: 129.7) == [.click(p, count: 1, secondary: true)], "stationary second touch retains long-press context menu")
        precondition(drag.end(p, time: 129.8).isEmpty)
        drag.begin(p, tool: .finger, time: 129.9, scrollFingerSwipes: true)
        precondition(drag.move(moved, time: 129.92) == [.scrollBegin(p, time: 129.9), .scroll(moved, time: 129.92)], "context menu cannot arm a later drag")
        var smart = DirectContactGesture()
        smart.begin(p, tool: .finger, time: 140, scrollFingerSwipes: true, awaitTarget: true)
        precondition(smart.move(moved, time: 140.02).isEmpty && smart.awaitingTarget)
        precondition(smart.resolveTarget(.drag, time: 140.04))
        precondition(smart.move(moved, time: 140.02) == [.down(p), .move(moved)], "title/slider hint must drag immediately and replay deferred motion")
        precondition(!smart.resolveTarget(.scroll, time: 140.05), "committed intent cannot change")
        precondition(smart.end(moved, time: 140.1) == [.move(moved), .up(moved)])
        smart.begin(p, tool: .finger, time: 141, scrollFingerSwipes: true, awaitTarget: true)
        precondition(smart.resolveTarget(.scroll, time: 141.04))
        precondition(smart.move(moved, time: 141.3) == [.scrollBegin(p, time: 141), .scroll(moved, time: 141.3)], "known scroll area remains scroll after a pause")
        smart.reset(); smart.begin(p, tool: .finger, time: 142, scrollFingerSwipes: true, awaitTarget: true)
        precondition(!smart.resolveTarget(.drag, time: 142.2), "late AX response cannot choose the gesture")
        smart.expireTarget()
        precondition(smart.move(moved, time: 142.03) == [.scrollBegin(p, time: 142), .scroll(moved, time: 142.03)], "timeout replays the original sample without losing movement")
        smart.reset(); smart.begin(p, tool: .finger, time: 143, scrollFingerSwipes: true, awaitTarget: true)
        precondition(smart.move(moved, time: 143.15) == [.scrollBegin(p, time: 143), .scroll(moved, time: 143.15)])
        precondition(!smart.resolveTarget(.drag, time: 143.16))
        smart.reset(); smart.begin(p, tool: .finger, time: 144, scrollFingerSwipes: true, awaitTarget: true)
        precondition(smart.end(p, time: 144.04) == [.click(p, count: 1, secondary: false)], "stationary tap never waits for AX")
        smart.begin(p, tool: .finger, time: 144.1, scrollFingerSwipes: true, awaitTarget: true)
        precondition(!smart.awaitingTarget && !smart.resolveTarget(.scroll, time: 144.11))
        precondition(smart.move(moved, time: 144.12) == [.down(p), .move(moved)], "explicit tap-drag overrides a scroll-area hint")
        smart.reset(); smart.begin(p, tool: .pencil, time: 145, scrollFingerSwipes: true, pencilTablet: true, awaitTarget: true)
        precondition(!smart.awaitingTarget && !smart.resolveTarget(.scroll, time: 145.01))
        smart.reset(); smart.begin(p, tool: .finger, time: 146, scrollFingerSwipes: true, awaitTarget: true)
        precondition(smart.resolveTarget(.automatic, time: 146.02))
        precondition(smart.move(moved, time: 146.03) == [.scrollBegin(p, time: 146), .scroll(moved, time: 146.03)], "unsupported or permission-denied apps retain normal gestures")
        smart.reset()
        precondition(!smart.resolveTarget(.drag, time: 146.04))
        let image = CGRect(x: 0, y: 0, width: 1000, height: 1000)
        let slider = GuestTouchObject(kind: 4, capabilities: 65, bounds: CGRect(x: 0, y: 0, width: 1, height: 1))!
        smart.begin(p, tool: .finger, time: 150, scrollFingerSwipes: true, awaitTarget: true)
        precondition(smart.resolveTarget(.drag, time: 150.01, object: slider, imageFrame: image))
        precondition(smart.move(CGPoint(x: 100, y: 208), time: 150.02).isEmpty, "cross-axis jitter cannot start a slider drag")
        precondition(smart.move(CGPoint(x: 103, y: 209), time: 150.03) == [.down(p), .move(CGPoint(x: 103, y: 200))], "slider moves after two points, aligned to its reported axis")
        precondition(smart.end(CGPoint(x: 104, y: 210), time: 150.04) == [.move(CGPoint(x: 104, y: 200)), .up(CGPoint(x: 104, y: 200))])
        let button = GuestTouchObject(kind: 9, capabilities: 16, bounds: CGRect(x: 0.09, y: 0.19, width: 0.1, height: 0.04))!
        smart.begin(p, tool: .finger, time: 151, scrollFingerSwipes: true, awaitTarget: true)
        precondition(smart.resolveTarget(.automatic, time: 151.01, object: button, imageFrame: image))
        precondition(smart.move(CGPoint(x: 125, y: 200), time: 151.02).isEmpty)
        precondition(smart.end(CGPoint(x: 125, y: 200), time: 151.03) == [.click(p, count: 1, secondary: false)], "motion inside a standalone button remains a press")
        smart.reset(); smart.begin(p, tool: .finger, time: 152, scrollFingerSwipes: true, awaitTarget: true)
        _ = smart.resolveTarget(.automatic, time: 152.01, object: button, imageFrame: image)
        precondition(smart.move(CGPoint(x: 250, y: 200), time: 152.02).isEmpty)
        precondition(smart.end(p, time: 152.03).isEmpty, "leaving a button cancels its pending press")
        let scrollingButton = GuestTouchObject(kind: 9, capabilities: 18, bounds: button.bounds)!
        smart.reset(); smart.begin(p, tool: .finger, time: 153, scrollFingerSwipes: true, awaitTarget: true)
        _ = smart.resolveTarget(.scroll, time: 153.01, object: scrollingButton, imageFrame: image)
        precondition(smart.move(moved, time: 153.02) == [.scrollBegin(p, time: 153), .scroll(moved, time: 153.02)], "button in scroll content must still allow scrolling")
        let splitter = GuestTouchObject(kind: 6, capabilities: 129, bounds: CGRect(x: 0, y: 0, width: 1, height: 1))!
        smart.reset(); smart.begin(p, tool: .finger, time: 154, scrollFingerSwipes: true, awaitTarget: true)
        _ = smart.resolveTarget(.drag, time: 154.01, object: splitter, imageFrame: image)
        precondition(smart.move(CGPoint(x: 103, y: 200), time: 154.02) == [.down(p), .move(CGPoint(x: 103, y: 200))], "splitter orientation describes its bar, not necessarily movement axis")
        let smallButton = GuestTouchObject(kind: 9, capabilities: 16, bounds: CGRect(x: 0.093, y: 0.193, width: 0.014, height: 0.014))!
        smart.reset(); smart.begin(p, tool: .finger, time: 155, scrollFingerSwipes: true, awaitTarget: true)
        _ = smart.resolveTarget(.automatic, time: 155.01, object: smallButton, imageFrame: image)
        precondition(smart.end(CGPoint(x: 110, y: 200), time: 155.04) == [.click(p, count: 1, secondary: false)], "small buttons tolerate touch-up jitter while clicking at the original hit")
        print("PASS: contact/tap-drag, semantic press/scroll/precise controls, target timeout/replay and Pencil isolation")
    }
}
